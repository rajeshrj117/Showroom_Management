/**
 * Helper to create a historical birth or anniversary date (e.g. 1986 or 2015)
 * whose month & day matches (today + dayOffset).
 */
function celebrationDateWithOffset(year: number, dayOffset: number, ref: Date = new Date()): string {
  const target = new Date(
    ref.getFullYear(),
    ref.getMonth(),
    ref.getDate() + dayOffset
  );
  const m = String(target.getMonth() + 1).padStart(2, "0");
  const d = String(target.getDate()).padStart(2, "0");
  return `${year}-${m}-${d}`;
}

